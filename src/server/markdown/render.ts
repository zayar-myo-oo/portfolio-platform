import { unified, type Plugin } from "unified";
import remarkParse from "remark-parse";
import remarkGfm from "remark-gfm";
import remarkDirective from "remark-directive";
import remarkRehype from "remark-rehype";
import rehypeSanitize, { defaultSchema, type Options as SanitizeSchema } from "rehype-sanitize";
import rehypeSlug from "rehype-slug";
import rehypeShiki from "@shikijs/rehype";
import rehypeStringify from "rehype-stringify";
import { visit, SKIP } from "unist-util-visit";
import { toString as hastToString } from "hast-util-to-string";
import { h } from "hastscript";
import type { Element, ElementContent, Root as HastRoot } from "hast";
import type { Root as MdastRoot, Code, Paragraph, Text } from "mdast";
import type { ContainerDirective, LeafDirective, TextDirective } from "mdast-util-directive";
import type { BundledLanguage, ShikiTransformer } from "shiki";
import { architectureToHast } from "./architecture-hast";

/**
 * Markdown → sanitised HTML.
 *
 * Content is stored as Markdown (+ directives) rather than executable MDX:
 * database-stored MDX would be a server-side code-execution vector. Rich
 * blocks are provided through a fixed vocabulary instead:
 *
 *   :::note / :::tip / :::warning / :::important   callouts (optional [Title])
 *   ```architecture                                 system diagram (see lib/architecture)
 *   ```ts title="server/data.ts"                     code block with filename
 *   ![alt](/media/… "Caption")                        figure with caption
 *
 * Pipeline order matters: sanitise first (removing anything the author could
 * inject), then add trusted structure (heading ids, diagrams, highlighted
 * code, figures) that the sanitiser would otherwise strip.
 */

export type TocItem = { id: string; text: string; depth: 2 | 3 };
export type RenderedMarkdown = { html: string; toc: TocItem[] };

const CALLOUTS = new Set(["note", "tip", "warning", "important"]);

// ── remark plugins ──────────────────────────────────────────────────────────

/** Turn known directives into callouts; restore unknown ones as plain text. */
const remarkDirectives: Plugin<[], MdastRoot> = () => (tree) => {
  visit(tree, (node, index, parent) => {
    if (node.type === "containerDirective") {
      const directive = node as ContainerDirective;
      if (CALLOUTS.has(directive.name)) {
        const data = (directive.data ??= {});
        data.hName = "aside";
        data.hProperties = { className: ["callout", `callout-${directive.name}`] };
        const first = directive.children[0];
        const hasLabel = first?.type === "paragraph" && first.data?.directiveLabel;
        const title: Paragraph = hasLabel
          ? (first as Paragraph)
          : { type: "paragraph", children: [{ type: "text", value: directive.name }] };
        title.data = { ...title.data, hName: "p", hProperties: { className: ["callout-title"] } };
        if (!hasLabel) directive.children.unshift(title);
      } else {
        (directive.data ??= {}).hName = "div";
      }
      return;
    }
    if ((node.type === "textDirective" || node.type === "leafDirective") && parent && index !== undefined) {
      const directive = node as TextDirective | LeafDirective;
      const prefix = node.type === "leafDirective" ? "::" : ":";
      const label = directive.children.map((child) => ("value" in child ? child.value : "")).join("");
      const text: Text = { type: "text", value: `${prefix}${directive.name}${label ? `[${label}]` : ""}` };
      if (node.type === "leafDirective") {
        parent.children.splice(index, 1, { type: "paragraph", children: [text] } as Paragraph);
      } else {
        parent.children.splice(index, 1, text);
      }
      return [SKIP, index];
    }
  });
};

/** Keep the fence meta string (e.g. title="…") so Shiki can read it. */
const remarkCodeMeta: Plugin<[], MdastRoot> = () => (tree) => {
  visit(tree, "code", (node: Code) => {
    if (!node.meta) return;
    const data = (node.data ??= {});
    data.hProperties = { ...(data.hProperties ?? {}), metastring: node.meta.slice(0, 200) };
  });
};

// ── sanitise schema ─────────────────────────────────────────────────────────

const baseAttributes = defaultSchema.attributes ?? {};
const sanitizeSchema: SanitizeSchema = {
  ...defaultSchema,
  // Never keep author-controlled ids/names; trusted ids are added later.
  clobber: [],
  tagNames: [...(defaultSchema.tagNames ?? []), "aside", "figure", "figcaption", "mark", "u"],
  attributes: {
    ...baseAttributes,
    "*": (baseAttributes["*"] ?? []).filter((attr) => attr !== "id" && attr !== "name"),
    // Footnote anchors generated by remark-gfm
    a: [...(baseAttributes.a ?? []), "id"],
    li: [...(baseAttributes.li ?? []), "id"],
    h2: [...(baseAttributes.h2 ?? []), "id"],
    code: [...(baseAttributes.code ?? []), "metastring"],
    aside: [["className", "callout", ...[...CALLOUTS].map((name) => `callout-${name}`)]],
    p: [["className", "callout-title"]],
    img: [...(baseAttributes.img ?? []), "title"],
  },
  protocols: {
    ...defaultSchema.protocols,
    src: ["http", "https"],
  },
};

// ── rehype plugins (post-sanitise, trusted structure) ───────────────────────

/** ```architecture fences → server-rendered diagram. */
const rehypeArchitecture: Plugin<[], HastRoot> = () => (tree) => {
  visit(tree, "element", (node: Element, index, parent) => {
    if (node.tagName !== "pre" || !parent || index === undefined) return;
    const code = node.children.find((child): child is Element => child.type === "element" && child.tagName === "code");
    const classes = (code?.properties.className as string[] | undefined) ?? [];
    if (!code || !classes.includes("language-architecture")) return;
    parent.children.splice(index, 1, architectureToHast(hastToString(code)));
    return [SKIP, index];
  });
};

function parseTitle(meta: string | undefined): string | undefined {
  if (!meta) return undefined;
  const match = /(?:title|file)=["']([^"']{1,120})["']/.exec(meta);
  return match?.[1];
}

const codeMetaTransformer: ShikiTransformer = {
  name: "portfolio:code-meta",
  pre(node) {
    const meta = (this.options.meta as { __raw?: string } | undefined)?.__raw;
    const title = parseTitle(meta);
    if (title) node.properties["data-title"] = title;
    node.properties["data-lang"] = this.options.lang;
    node.properties.tabindex = "0";
  },
};

/** Wrap highlighted <pre> in a figure with filename/language and copy button. */
const rehypeCodeFigure: Plugin<[], HastRoot> = () => (tree) => {
  visit(tree, "element", (node: Element, index, parent) => {
    if (node.tagName !== "pre" || !parent || index === undefined) return;
    if (parent.type === "element" && parent.tagName === "figure") return;
    const title = node.properties["data-title"] ?? node.properties.dataTitle;
    const lang = String(node.properties["data-lang"] ?? node.properties.dataLang ?? "text");
    const figure = h("figure", { className: ["code-block"] }, [
      h("figcaption", { className: ["code-block-header"] }, [
        h("span", { className: ["code-block-title"] }, String(title ?? lang)),
        h("button", { type: "button", className: ["code-copy"], "data-copy": "" }, "Copy"),
      ]),
      node,
    ]);
    parent.children.splice(index, 1, figure);
    return [SKIP, index + 1];
  });
};

/** Lazy images; titled images become figures with captions. */
const rehypeMedia: Plugin<[], HastRoot> = () => (tree) => {
  visit(tree, "element", (node: Element, index, parent) => {
    if (node.tagName !== "img") return;
    node.properties.loading = "lazy";
    node.properties.decoding = "async";
    const caption = node.properties.title;
    if (!caption || !parent || index === undefined || parent.type !== "element") return;
    delete node.properties.title;
    // Markdown wraps images in <p>; replace a lone-image paragraph with a figure.
    if (parent.tagName === "p" && parent.children.filter((c) => c.type === "element").length === 1) {
      parent.tagName = "figure";
      parent.properties = { className: ["md-figure"] };
      parent.children = [node, h("figcaption", String(caption))];
    }
  });
};

/** External links open in a new tab, safely, and get a cursor hint. */
const rehypeLinks: Plugin<[], HastRoot> = () => (tree) => {
  visit(tree, "element", (node: Element) => {
    if (node.tagName !== "a") return;
    const href = String(node.properties.href ?? "");
    if (/^https?:\/\//i.test(href)) {
      node.properties.target = "_blank";
      node.properties.rel = ["noopener", "noreferrer"];
      node.properties["data-cursor"] = "open";
    }
  });
};

function rehypeToc(toc: TocItem[]): Plugin<[], HastRoot> {
  return () => (tree) => {
    visit(tree, "element", (node: Element) => {
      if ((node.tagName === "h2" || node.tagName === "h3") && typeof node.properties.id === "string") {
        if (node.properties.id.startsWith("footnote")) return;
        toc.push({ id: node.properties.id, text: hastToString(node), depth: node.tagName === "h2" ? 2 : 3 });
      }
    });
  };
}

/** Add a "#" anchor link to headings (keyboard-accessible, hidden visually until hover/focus). */
const rehypeHeadingAnchors: Plugin<[], HastRoot> = () => (tree) => {
  visit(tree, "element", (node: Element) => {
    if (!["h2", "h3"].includes(node.tagName) || typeof node.properties.id !== "string") return;
    const anchor: ElementContent = h(
      "a",
      { href: `#${node.properties.id}`, className: ["heading-anchor"], ariaLabel: `Link to section: ${hastToString(node)}` },
      "#",
    );
    node.children.push(anchor);
  });
};

// ── public API ──────────────────────────────────────────────────────────────

const SHIKI_LANGS: BundledLanguage[] = [
  "ts", "tsx", "js", "jsx", "json", "bash", "shell", "sql", "java", "kotlin", "python", "go", "rust",
  "yaml", "toml", "html", "css", "diff", "dockerfile", "prisma", "graphql", "markdown",
];

export async function renderMarkdown(markdown: string | null | undefined): Promise<RenderedMarkdown> {
  if (!markdown?.trim()) return { html: "", toc: [] };

  const toc: TocItem[] = [];
  const file = await unified()
    .use(remarkParse)
    .use(remarkGfm)
    .use(remarkDirective)
    .use(remarkDirectives)
    .use(remarkCodeMeta)
    .use(remarkRehype) // raw HTML in Markdown is dropped (allowDangerousHtml: false)
    .use(rehypeSanitize, sanitizeSchema)
    .use(rehypeSlug)
    .use(rehypeArchitecture)
    .use(rehypeShiki, {
      themes: { light: "vitesse-light", dark: "vitesse-dark" },
      defaultColor: false,
      langs: SHIKI_LANGS,
      fallbackLanguage: "text",
      defaultLanguage: "text",
      transformers: [codeMetaTransformer],
      onError: () => {},
    })
    .use(rehypeCodeFigure)
    .use(rehypeMedia)
    .use(rehypeLinks)
    .use(rehypeToc(toc))
    .use(rehypeHeadingAnchors)
    .use(rehypeStringify)
    .process(markdown);

  return { html: String(file), toc };
}

/** Render several optional Markdown fields at once (case-study sections). */
export async function renderFields<K extends string>(
  fields: Record<K, string | null | undefined>,
): Promise<Record<K, string>> {
  const entries = await Promise.all(
    (Object.entries(fields) as Array<[K, string | null | undefined]>).map(
      async ([key, value]) => [key, (await renderMarkdown(value)).html] as const,
    ),
  );
  return Object.fromEntries(entries) as Record<K, string>;
}
